"""Check that each shot's focal text is readable in the README.

Decodes the finished movie at README width at the middle of each hold, and measures the cap
height of the text lines in two places: inside the focal ring, which is the app itself, and
inside the callout, which repeats real on-screen text. A shot passes when either is at least
the minimum. plan.py checks that the callout text is text the take showed. Also writes the
crops, one full-size and one README-size frame per shot, and a contact sheet with a frame
every two seconds."""
import argparse
import json
from pathlib import Path
import subprocess

from PIL import Image

from ink import ink_mask, line_caps

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('timeline', type=Path)
parser.add_argument('movie', type=Path)
parser.add_argument('out', type=Path, help='directory for crops, frames, sheet.png and legibility.md')
parser.add_argument('--width', type=int, default=900)
parser.add_argument('--minimum', type=float, default=9.5)
args = parser.parse_args()
timeline = json.loads(args.timeline.read_text())
W = 1920
APP = timeline['app']
INSET = 6  # CSS px inside a ring or callout edge, clear of its stroke and glow
args.out.mkdir(parents=True, exist_ok=True)
k = args.width / W


def frame(t, width):
    data = subprocess.run(['ffmpeg', '-v', 'error', '-ss', f'{t:.3f}', '-i', str(args.movie), '-frames:v', '1',
                           '-vf', f'scale={width}:-1:flags=lanczos', '-f', 'image2pipe', '-c:v', 'png', '-'],
                          check=True, capture_output=True).stdout
    path = args.out / 'tmp.png'
    path.write_bytes(data)
    image = Image.open(path)
    image.load()
    path.unlink()
    return image


def caps_in(image, box, name):
    """Cap heights of the text lines inside a box given in the app's CSS px."""
    left, top = APP['x'] + (box['x'] + INSET) * APP['scale'], APP['y'] + (box['y'] + INSET) * APP['scale']
    right = APP['x'] + (box['x'] + box['width'] - INSET) * APP['scale']
    bottom = APP['y'] + (box['y'] + box['height'] - INSET) * APP['scale']
    crop = image.crop((round(left * k), round(top * k), round(right * k), round(bottom * k))).convert('L')
    crop.save(args.out / f'crop-{name}.png')
    return line_caps(ink_mask(crop, threshold=50), gap=1, smallest=5)


rows, failures = [], []
for index, shot in enumerate(s for s in timeline['shots'] if 'ring' in s):
    t = (shot['hold'][0] + shot['hold'][1]) / 2
    name = f'{index + 1:02d}-{shot["name"].replace(" ", "-")}'
    small = frame(t, args.width)
    in_app = caps_in(small, shot['ring'], name + '-app')
    in_callout = caps_in(small, shot['callout']['box'], name + '-callout')
    small.save(args.out / f'frame-{name}-{args.width}.png')
    frame(t, 2560).save(args.out / f'frame-{name}.png')
    app_cap = min(in_app) if in_app else 0
    callout_cap = in_callout[-1] if in_callout else 0
    passed = max(app_cap, callout_cap) >= args.minimum
    if not passed:
        failures.append(f'{shot["name"]}: focal text is {app_cap}px in the app and {callout_cap}px in the callout')
    rows.append(f'| {shot["name"]} | {t:.1f} | {app_cap} | {callout_cap} | {"pass" if passed else "fail"} '
                f'| {shot["callout"]["text"]} |')

tiles = [frame(t, args.width) for t in range(0, int(timeline['duration']) + 1, 2)]
columns = 4
sheet = Image.new('RGB', (columns * args.width, -(-len(tiles) // columns) * tiles[0].height), '#222')
for i, tile in enumerate(tiles):
    sheet.paste(tile, ((i % columns) * args.width, (i // columns) * tile.height))
sheet.save(args.out / 'sheet.png')

report = ['# Legibility at README width', '',
          f'Generated by `docs/demo/channels/motion/legibility.py` from `{args.movie.name}`, decoded at {args.width} px '
          'wide at the middle of each hold. App is the smallest cap height of the text lines inside the focal ring. '
          'Callout is the cap height of the main line of the callout, which repeats real on-screen text. A shot '
          f'passes when either is at least {args.minimum} px.', '',
          '| Shot | Time (s) | App cap (px) | Callout cap (px) | Result | Callout text |',
          '|---|---:|---:|---:|---|---|', *rows, '',
          f'Result: {"fail" if failures else "pass"}.']
(args.out / 'legibility.md').write_text('\n'.join(report) + '\n')
print('\n'.join(report))
if failures:
    parser.error('\n'.join(failures))
