"""Check that each shot's focal text is readable in the README.

Decodes the finished movie at README width, crops every focal ring at the middle of its
hold, and measures the cap height of each text line inside it. Fails when any line is
under the minimum. Also writes the crops, one full-size and one README-size frame per
shot, and a contact sheet with a frame every two seconds."""
import argparse
import json
from pathlib import Path
import subprocess

from PIL import Image

from ink import ink_mask, line_caps

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('timeline', type=Path)
parser.add_argument('movie', type=Path)
parser.add_argument('out', type=Path, help='directory for crops, frames, sheet.png and legibility.md')
parser.add_argument('--width', type=int, default=900)
parser.add_argument('--minimum', type=float, default=9.5)
args = parser.parse_args()
timeline = json.loads(args.timeline.read_text())
W, BAND = 1920, timeline['band']
CENTER_Y = BAND + (1080 - BAND) / 2
INSET = 8  # CSS px inside the ring, clear of its stroke and glow
args.out.mkdir(parents=True, exist_ok=True)


def frame(t, width):
    data = subprocess.run(['ffmpeg', '-v', 'error', '-ss', f'{t:.3f}', '-i', str(args.movie), '-frames:v', '1',
                           '-vf', f'scale={width}:-1:flags=lanczos', '-f', 'image2pipe', '-c:v', 'png', '-'],
                          check=True, capture_output=True).stdout
    path = args.out / 'tmp.png'
    path.write_bytes(data)
    image = Image.open(path)
    image.load()
    path.unlink()
    return image


rows, failures = [], []
for index, shot in enumerate(s for s in timeline['shots'] if 'ring' in s):
    t = (shot['hold'][0] + shot['hold'][1]) / 2
    cx, cy, zoom = shot['camera'][-1][1]
    ring, k = shot['ring'], args.width / W
    left = (W / 2 + (ring['x'] + INSET - cx) * zoom) * k
    top = (CENTER_Y + (ring['y'] + INSET - cy) * zoom) * k
    right = (W / 2 + (ring['x'] + ring['width'] - INSET - cx) * zoom) * k
    bottom = (CENTER_Y + (ring['y'] + ring['height'] - INSET - cy) * zoom) * k
    small = frame(t, args.width)
    crop = small.crop((round(left), round(top), round(right), round(bottom))).convert('L')
    caps = line_caps(ink_mask(crop, threshold=50), gap=1, smallest=5)
    name = f'{index + 1:02d}-{shot["name"].replace(" ", "-")}'
    crop.save(args.out / f'crop-{name}.png')
    small.save(args.out / f'frame-{name}-{args.width}.png')
    frame(t, 2560).save(args.out / f'frame-{name}.png')
    smallest = min(caps) if caps else 0
    if smallest < args.minimum:
        failures.append(f'{shot["name"]}: smallest focal line is {smallest}px at {args.width}px')
    geometry = shot['capCss'] * zoom * args.width / W
    rows.append(f'| {shot["name"]} | {t:.1f} | {shot["zoom"]:.2f} | {geometry:.1f} | {smallest} | '
                f'{", ".join(map(str, caps))} |')

duration = timeline['duration']
tiles = [frame(t, args.width) for t in range(0, int(duration) + 1, 2)]
columns = 4
sheet = Image.new('RGB', (columns * args.width, -(-len(tiles) // columns) * tiles[0].height), '#222')
for i, tile in enumerate(tiles):
    sheet.paste(tile, ((i % columns) * args.width, (i // columns) * tile.height))
sheet.save(args.out / 'sheet.png')

report = ['# Legibility at README width', '',
          f'Generated by `docs/demo/channels/motion/legibility.py` from `{args.movie.name}`. Each ring is cropped '
          f'{INSET} CSS px inside its edge at the middle of its hold, from a frame decoded at {args.width} px wide. '
          'Geometry is the smallest focal cap height measured in the source frame, scaled by the shot zoom. Measured '
          'is the cap height of each text line found in the crop, in pixels; the check uses the smallest.', '',
          '| Shot | Time (s) | Zoom | Geometry cap (px) | Smallest measured cap (px) | Measured caps by line (px) |',
          '|---|---:|---:|---:|---:|---|', *rows, '',
          f'Minimum: {args.minimum} px. Result: {"fail" if failures else "pass"}.']
(args.out / 'legibility.md').write_text('\n'.join(report) + '\n')
print('\n'.join(report))
if failures:
    parser.error('\n'.join(failures))
