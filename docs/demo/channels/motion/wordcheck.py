"""Fail when a banned word appears anywhere in the finished Channels movie.

Checks the text the render draws (captions, callouts, cards, labels, the end card and the agent
windows' rows) and reads every half second of the decoded movie with Tesseract, so the real app
pixels are checked too. The default word is "operator": the person watching is "you"."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('take', type=Path, help='take directory with timeline.json and panes.js')
parser.add_argument('movie', type=Path)
parser.add_argument('report', type=Path, help='Markdown report to write')
parser.add_argument('--word', default='operator')
parser.add_argument('--every', type=float, default=0.5)
args = parser.parse_args()
# Tesseract reads o as 0 and e as 3 now and then; match those too.
pattern = re.compile(''.join({'o': '[o0]', 'e': '[e3]'}.get(c, re.escape(c)) for c in args.word.lower()), re.I)

timeline = json.loads((args.take / 'timeline.json').read_text())
drawn = [('caption', c['text']) for c in timeline['captions']]
for shot in timeline['shots']:
    drawn += [('callout', shot['callout']['who']), ('callout', shot['callout']['text']), ('label', shot.get('label', ''))]
drawn += [('card', card['text']) for card in timeline['cards']]
drawn += [('scene source', line) for line in (Path(__file__).with_name('scene.mjs')).read_text().splitlines()]
drawn += [('agent window', row) for row in re.sub(r'\\u001b\[[0-9;?]*[A-Za-z]', '', (args.take / 'panes.js').read_text()).split('", "')]
hits = [f'{kind}: {text.strip()[:120]}' for kind, text in drawn if text and pattern.search(text)]

frames, t = 0, 0.0
duration = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(args.movie)]))
with tempfile.TemporaryDirectory(dir=args.report.parent) as scratch:
    png = Path(scratch) / 'frame.png'
    while t < duration:
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{t:.2f}', '-i', str(args.movie), '-frames:v', '1', str(png)], check=True)
        text = subprocess.run(['tesseract', str(png), '-', '--psm', '11'], check=True, capture_output=True, text=True).stdout
        for line in text.splitlines():
            if pattern.search(line):
                hits.append(f'movie at {t:.1f}s: {line.strip()[:120]}')
        frames += 1
        t += args.every

lines = [f'# "{args.word}" check', '',
         f'Generated by `docs/demo/channels/motion/wordcheck.py` on `{args.movie.name}` ({duration:.1f} s).', '',
         f'- Drawn text checked: {len(drawn)} strings (captions, callouts, cards, labels, scene source, agent-window rows).',
         f'- Movie frames read with Tesseract: {frames}, one every {args.every:g} s at full size.',
         f'- Matches: {len(hits)}.', '', *[f'  - {hit}' for hit in hits], '',
         f'Result: {"fail" if hits else "pass"}.']
args.report.write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
if hits:
    parser.exit(1)
