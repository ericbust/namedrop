import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const project = dirname(fileURLToPath(import.meta.url));
const dist = join(project, "dist");
const dashboard = resolve(project, "../../src/dashboard");
const output = join(dashboard, "channels");
const table = join(dashboard, "channels_bundle.rs");
const check = process.argv[2] === "--check";
if (process.argv.length > 3 || (process.argv[2] && !check)) {
  throw new Error("usage: node bundle.mjs [--check]");
}

function files(root) {
  const found = [];
  function visit(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile())
        found.push(relative(root, path).split(sep).join("/"));
      else throw new Error(`unexpected bundle entry: ${path}`);
    }
  }
  visit(root);
  return found.sort();
}

const names = files(dist);
if (!names.includes("index.html"))
  throw new Error("Vite dist has no index.html");
const source = [
  "// Generated by experimental/channels/bundle.mjs. Do not edit.",
  "pub(super) fn get(path: &str) -> Option<&'static [u8]> {",
  "    match path {",
  ...names.flatMap((name) => {
    const arm = `${JSON.stringify(`/${name}`)} => Some(include_bytes!(${JSON.stringify(`channels/${name}`)}).as_slice()),`;
    return arm.length <= 92
      ? [`        ${arm}`]
      : [
          `        ${JSON.stringify(`/${name}`)} => {`,
          `            Some(include_bytes!(${JSON.stringify(`channels/${name}`)}).as_slice())`,
          "        }",
        ];
  }),
  "        _ => None,",
  "    }",
  "}",
  "",
].join("\n");

if (check) {
  const actual = files(output);
  const differences = [];
  for (const name of new Set([...names, ...actual])) {
    if (!names.includes(name)) differences.push(`extra: ${name}`);
    else if (!actual.includes(name)) differences.push(`missing: ${name}`);
    else if (
      !readFileSync(join(dist, name)).equals(readFileSync(join(output, name)))
    )
      differences.push(`changed: ${name}`);
  }
  if (readFileSync(table, "utf8") !== source)
    differences.push("changed: channels_bundle.rs");
  if (differences.length)
    throw new Error(`Channels bundle is stale:\n${differences.join("\n")}`);
  console.log(`Channels bundle matches ${names.length} built files`);
} else {
  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });
  for (const name of names) {
    const destination = join(output, name);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, readFileSync(join(dist, name)));
  }
  writeFileSync(table, source);
  console.log(`Wrote ${names.length} Channels bundle files`);
}
